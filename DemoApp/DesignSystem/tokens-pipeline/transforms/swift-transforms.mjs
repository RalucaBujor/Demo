// transforms/swift-transforms.mjs

export function registerSwiftTransforms(StyleDictionary) {
  //
  // name transform
  //

  StyleDictionary.registerTransform({
    name: 'name/swift-camel',
    type: 'name',

    transform: (token) => {
      const path = token.path.filter((p) => p !== 'color');

      return path
        .map((segment, index) =>
          index === 0
            ? segment
            : segment.charAt(0).toUpperCase() + segment.slice(1)
        )
        .join('');
    }
  });

  //
  // color transform
  //

  StyleDictionary.registerTransform({
    name: 'color/swiftui-literal',
    type: 'value',
    transitive: true,

    filter: (token) => {
      const type = token.$type ?? token.type;
      return type === 'color';
    },

    transform: (token) => {
      const value = token.$value ?? token.value;

      if (typeof value !== 'string' || !value.startsWith('#')) {
        return value;
      }

      const hex = value.replace('#', '');

      const r = parseInt(hex.substring(0, 2), 16) / 255;
      const g = parseInt(hex.substring(2, 4), 16) / 255;
      const b = parseInt(hex.substring(4, 6), 16) / 255;

      const a =
        hex.length === 8
          ? parseInt(hex.substring(6, 8), 16) / 255
          : 1;

      return `Color(
        red: ${r.toFixed(4)},
        green: ${g.toFixed(4)},
        blue: ${b.toFixed(4)},
        opacity: ${a.toFixed(4)}
      )`;
    }
  });

  //
  // transform group
  //

  StyleDictionary.registerTransformGroup({
    name: 'swiftui-colors',
    transforms: [
      'name/swift-camel',
      'color/swiftui-literal'
    ]
  });

  //
  // Swift format
  //

  StyleDictionary.registerFormat({
    name: 'swift/color-struct',

    format: ({ dictionary, options }) => {
      const { brandName, scheme, namespace, accessLevel = 'public' } = options;

      const tokens = dictionary.allTokens.filter((token) => {
        const type = token.$type ?? token.type;
        return type === 'color';
      });

      const lines = tokens.map(
        (token) => `    ${accessLevel} static let ${token.name} = ${token.$value}`
      );

      return `// Auto-generated by Style Dictionary. DO NOT EDIT.

import SwiftUI

${accessLevel} enum ${brandName}${scheme}${namespace} {

${lines.join('\n')}

}
`;
    }
  });
}